"""Тесты слоя multi-intent: формулировки из живого прогона V11.

Запуск: python test_multi_intent.py
Ничего не поднимает — работает прямо с базой знаний, без сервера и API-ключей.
"""
import sys
sys.path.insert(0, '.')
from backend.rag_index import local_answer

BOT_HISTORY = [
    {"role": "user", "content": "Расскажи про бота для записи клиентов"},
    {"role": "assistant", "content": "Бот может отвечать по материалам компании"},
]

CASES = [
    # (вопрос, должно встретиться всё из, должно встретиться хотя бы одно из, история)
    ("Лендинг для автомойки, и сколько стоит?", ["12 000"], [], None),
    ("Можете сделать бот для СТО, сколько он стоит и что умеет?", ["15 000", "autoneuro"], [], None),
    ("Нужен бот чтобы принимал фото, голос и отвечал по прайсу — что предложишь?", [], ["фото"], None),
    ("Нужен лендинг, AI-бот и ролик — сколько всё вместе?", ["12 000", "15 000", "10 000"], [], None),
    ("Можешь сделать проморолик?", [], ["видео", "ролик"], None),
    ("Можно записаться завтра?", [], ["запись"], None),
    ("Где посмотреть твои реальные работы?", [], ["youtube"], None),
    ("Какие ещё проекты кроме трёх кейсов?", ["EDA", "TaskZero"], [], None),
    ("А сколько это будет стоить?", ["10 000", "12 000", "15 000"], [], None),
    ("А сколько это будет стоить?", ["15 000"], [], BOT_HISTORY),
    ("А сроки?", ["5–7"], [], BOT_HISTORY),
    # Отказы обязаны оставаться отказами
    ("Погода в Москве", ["нет точного ответа"], [], None),
    ("сколько", ["нет точного ответа"], [], None),
    ("сможешь сделать услугу уборки дома?", ["нет точного ответа"], [], None),
    ("asdf qwerty", ["нет точного ответа"], [], None),
    # Длинная фраза про чужую услугу не должна подхватывать тему из прошлой реплики
    ("сколько будет стоить уборка у меня дома какова цена Сколько будет стоить уборка дома?",
     ["нет точного ответа"], [], BOT_HISTORY),
    ("У меня две точки в разных районах города Минска, автомойки. Что мне сделать, как продумать?",
     ["нет точного ответа"], [], None),
]


def main() -> int:
    failed = 0
    for question, must_all, must_any, history in CASES:
        answer = local_answer(question, history=history).get("answer", "")
        low = answer.lower()
        ok = all(x.lower() in low for x in must_all) and (not must_any or any(x.lower() in low for x in must_any))
        if not ok:
            failed += 1
        print(f"{'OK  ' if ok else 'FAIL'} {question} => {answer[:110]}")
    print(f"\nВсего: {len(CASES)}, провалов: {failed}")
    return 1 if failed else 0


if __name__ == '__main__':
    raise SystemExit(main())
